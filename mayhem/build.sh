#!/usr/bin/env bash
#
# mayhem/build.sh — build glib's 32 OSS-Fuzz harnesses (sanitized, libFuzzer + standalone) and the
# unit-test subset that mayhem/test.sh runs (normal flags). Idempotent; resolves everything from the
# image (apt -dev packages, the gvdb submodule), never the network.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
export CC CXX

# glib casts function pointers (GDestroyNotify, GCompareFunc, ...) through incompatible types all
# over its API; with halting UBSan -fsanitize=function aborts on the first g_hash_table/GMarkup call.
# Only that one check is relaxed; ASan and every other UBSan check stay on and halting.
SAN="$SANITIZER_FLAGS"
[ -z "$SAN" ] || SAN="$SAN -fno-sanitize=function"

# Coverage instrumentation for the glib libraries themselves (what OSS-Fuzz does via CFLAGS): without
# it libFuzzer only sees edges in the harness file and Mayhem records ~0 edges.
COV="-fsanitize=fuzzer-no-link"

cd "$SRC"

# gvdb is a git submodule; `git clean -ffdX` removes it (subprojects/*/ is gitignored), so restore it
# from the in-image .git/modules (offline) when missing.
if [ ! -f subprojects/gvdb/meson.build ]; then
  git submodule update --init --depth 1 subprojects/gvdb
fi

MESON_OPTS=(-Dwrap_mode=nodownload -Dnls=disabled -Dselinux=disabled -Dlibelf=disabled -Dsysprof=disabled
            -Dman-pages=disabled -Ddocumentation=false -Dintrospection=disabled -Dxattr=false)

# 1) The project itself, sanitized, static libs (build dir under the gitignored /meson-build/).
FUZZ_B="$SRC/meson-build/fuzz"
if [ ! -f "$FUZZ_B/build.ninja" ]; then
  CFLAGS="-O1 $SAN $COV $DEBUG_FLAGS" LDFLAGS="$SAN $COV" \
    meson setup "$FUZZ_B" --default-library=static -Db_lundef=false -Dbuildtype=plain \
      -Dtests=false -Dglib_debug=disabled "${MESON_OPTS[@]}"
fi
ninja -C "$FUZZ_B" -j"$MAYHEM_JOBS" glib/libglib-2.0.a gmodule/libgmodule-2.0.a \
  gobject/libgobject-2.0.a gio/libgio-2.0.a

# 2) Every harness twice: libFuzzer binary + non-fuzzer standalone reproducer. Leak detection is
#    compiled out (lsan_off.o), ASan/UBSan stay on.
mkdir -p "$SRC/meson-build/obj"
$CXX $SAN $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.cc" -o "$SRC/meson-build/obj/lsan_off.o"
export PKG_CONFIG_PATH="$FUZZ_B/meson-uninstalled"
GLIB_CFLAGS="$(pkg-config --static --cflags gio-2.0 gmodule-2.0 gobject-2.0 glib-2.0)"
GLIB_LIBS="$(pkg-config --static --libs gio-2.0 gmodule-2.0 gobject-2.0 glib-2.0)"

# Without sanitizers (SANITIZER_FLAGS=) nothing provides the __sanitizer_cov_* callbacks the
# instrumented libraries reference, so the standalone reproducers get no-op stubs for them.
STUBS=""
if [ -z "$SANITIZER_FLAGS" ]; then
  OBJ="$SRC/meson-build/obj"
  { echo "/* generated by mayhem/build.sh */"
    nm -u "$FUZZ_B"/glib/libglib-2.0.a "$FUZZ_B"/gmodule/libgmodule-2.0.a "$FUZZ_B"/gobject/libgobject-2.0.a \
       "$FUZZ_B"/gio/libgio-2.0.a 2>/dev/null | awk '/__sanitizer_cov/ {print $2}' | sort -u \
      | sed 's/.*/void &(void) {}/'
    echo "void __sanitizer_cov_trace_pc_guard_init(void) {}"
  } | sort -u > "$OBJ/cov_stubs.c"
  $CC -c "$OBJ/cov_stubs.c" -o "$OBJ/cov_stubs.o"
  STUBS="$OBJ/cov_stubs.o"
fi
$CC -O1 $SAN $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$SRC/meson-build/obj/standalone_main.o"
export SAN COV DEBUG_FLAGS LIB_FUZZING_ENGINE GLIB_CFLAGS GLIB_LIBS SRC STUBS CC

build_harness() {
  local t="$1" o="$SRC/meson-build/obj"
  # shellcheck disable=SC2086
  $CC -O1 $SAN $COV $DEBUG_FLAGS -DFUZZING_BUILD_MODE_UNSAFE_FOR_PRODUCTION $GLIB_CFLAGS \
      -c "$SRC/fuzzing/$t.c" -o "$o/$t.o"
  # shellcheck disable=SC2086
  $CC $SAN "$o/$t.o" "$o/lsan_off.o" $LIB_FUZZING_ENGINE $GLIB_LIBS -o "$SRC/$t"
  # shellcheck disable=SC2086
  $CC $SAN "$o/$t.o" "$o/standalone_main.o" "$o/lsan_off.o" $STUBS $GLIB_LIBS -o "$SRC/$t-standalone"
}
export -f build_harness
xargs -a "$SRC/mayhem/targets.list" -P "$MAYHEM_JOBS" -I{} bash -c 'build_harness {}'

# 3) The unit-test subset, normal flags (no sanitizers), independent build tree; test.sh only runs it.
TEST_B="$SRC/meson-build/tests"
if [ ! -f "$TEST_B/build.ninja" ]; then
  env -u CFLAGS -u LDFLAGS CFLAGS="$COVERAGE_FLAGS" LDFLAGS="$COVERAGE_FLAGS" \
    meson setup "$TEST_B" -Dtests=true "${MESON_OPTS[@]}"
fi
ninja -C "$TEST_B" -j"$MAYHEM_JOBS" $(sed 's|^|glib/tests/|' "$SRC/mayhem/tests.list")
